export function getStudyPageMeta(relativePath: string, locale: StudyLocale): StudyPageMeta {
  const path = relativePath.replace(/\\/g, '/')
  const parts = path.split('/').filter(Boolean)
  const key = parts[0] === 'fr' ? parts[1] : parts[0]
  return (key && pages[key]?.[locale]) || fallback[locale]
}
